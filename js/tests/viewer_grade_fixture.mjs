/**
 * The shared fixture that holds the Python delivery grade to the viewer grade.
 *
 * A Deliver master is graded in Python (color/grading.py apply_grading, fed by
 * viewer_grade_kwargs from the payload the viewer sends). The picture on screen
 * is graded by the shader, which grade_render.test.mjs holds to gradePixelFull
 * in js/radiance_grade.js. This file builds a set of grade payloads and pixels,
 * grades them with gradePixelFull, and writes the result to
 * tests/fixtures/viewer_grade_parity.json, which
 * tests/test_viewer_grade_parity.py feeds through the Python grade.
 *
 * viewer_grade_fixture.test.mjs regenerates the fixture and compares it with the
 * committed file, so neither side can change without the other noticing.
 *
 * Regenerate: node js/tests/viewer_grade_fixture.mjs --write
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { gradePixelFull } from '../radiance_grade.js';

export const FIXTURE_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'tests', 'fixtures', 'viewer_grade_parity.json');

/** A curve table as the editor emits it: 256 RGBA entries, float32 values. */
function curveTable(fr, fg, fb) {
    const t = new Float32Array(1024);
    for (let i = 0; i < 256; i++) {
        const x = i / 255;
        t.set([fr(x), fg(x), fb(x), 1], i * 4);
    }
    return Array.from(t);
}

function hueTable() {
    const t = new Float32Array(1024);
    for (let i = 0; i < 256; i++) {
        const h = i / 255;
        t.set([0.5 + 0.05 * Math.sin(2 * Math.PI * h), 0.5 + 0.1 * Math.cos(2 * Math.PI * h), 0.5, 1], i * 4);
    }
    return Array.from(t);
}

