/** The delivery payload, in the field names gradePixelFull reads. */
function toState(g) {
    const { hue_shift, sourceGamut, ...rest } = g;
    return { ...rest, ...(hue_shift !== undefined ? { hueShift: hue_shift } : {}) };
}

export function buildFixture() {
    return {
        note: 'Generated by js/tests/viewer_grade_fixture.mjs from js/radiance_grade.js gradePixelFull. Do not edit.',
        pixels: PIXELS,
        cases: CASES.map(({ name, grading }) => ({
            name,
            grading,
            expected: PIXELS.map((px) => gradePixelFull(px, toState(grading), { gamut: grading.sourceGamut ?? 0 })),
        })),
    };
}

if (process.argv.includes('--write')) {
    writeFileSync(FIXTURE_PATH, JSON.stringify(buildFixture()) + '\n');
    console.log(`wrote ${FIXTURE_PATH}`);
}
